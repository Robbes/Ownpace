/**
 * A CONVENTION TWO COMMITS IN TWO HUNDRED FOLLOWED.
 *
 * `CONTRIBUTING.md` has said "Conventional Commits (`feat:`, `fix:`, `docs:`,
 * `chore:`, `refactor:`, `test:`...)" for as long as it has existed, and the
 * pull-request template repeats it in bold above the signature line. Measured
 * on 2026-09-21 over the last two hundred subjects on `main`: **two** follow
 * it, and both are dependabot's. Ninety-five are merge commits. The remaining
 * hundred-odd are prose, written by the people and agents who had read both
 * documents.
 *
 * That is the shape this repository keeps finding and keeps closing: a rule
 * that is documented, agreed, and enforced by nothing. `pnpm lint` does not
 * read commit messages, no CI job ever has, and the template's line is a line
 * in a template. So the rule was true in the sense that everyone would have
 * agreed with it, and false in the sense that nothing in the tree depended on
 * it.
 *
 * WHAT THIS CHECKS, and what it deliberately does not:
 *
 *  - Only the commits a pull request ADDS (`base..head`). Nothing reads or
 *    re-judges history: the hundred-odd prose subjects already on `main` stay
 *    exactly as they are, and no branch has to be rewritten to go green.
 *  - A MERGE COMMIT IS EXEMPT, detected by its parent count rather than by its
 *    subject text. This is not a courtesy — merging the base branch into a
 *    branch to resolve a conflict is the documented way to do it here, and it
 *    produces "Merge branch 'main' into …", which no convention covers. A
 *    check that failed on those would punish the correct move.
 *  - `Revert "…"` is exempt, because that subject is generated by GitHub and
 *    by `git revert`, and neither takes a format argument.
 *  - Nothing about LENGTH, mood, or a trailing full stop. Those are style
 *    opinions this project has not stated, and a gate that enforces unstated
 *    opinions is how a convention gets resented rather than followed.
 *
 * The type list lives here and `a-convention-two-of-two-hundred-commits-
 * followed.unit.test.ts` asserts that every type CONTRIBUTING.md NAMES is in
 * it — so a type somebody documents and this refuses is a failing test rather
 * than a confused contributor. It does not assert the reverse: CONTRIBUTING's
 * list ends in an ellipsis, so it was never a closed set.
 *
 * `.mjs` for the reason `audit-advisories.mjs` gives: this runs inside a CI
 * step and needs no type stripping on any Node this project has used.
 */

import { execFileSync } from 'node:child_process';

/**
 * The types a subject may carry.
 *
 * The six CONTRIBUTING.md names, plus the four the Conventional Commits spec's
 * own Angular preset defines and dependabot actually emits here (`ci(actions):
 * bump the actions group with 4 updates` is on `main` today, and a gate that
 * refused dependabot would be a gate somebody turns off), plus `revert` for the
 * hand-written form.
 */
export const TYPES = Object.freeze([
  'feat',
  'fix',
  'docs',
  'chore',
  'refactor',
  'test',
  'ci',
  'build',
  'perf',
  'style',
  'revert',
]);

/**
 * type, optional (scope), optional ! for a breaking change, ": ", a summary.
 *
 * The space after the colon is required by the spec and is the one part people
 * get wrong by accident, so it is matched rather than tolerated.
 */
const SUBJECT = /^([a-zA-Z]+)(\([^()\r\n]*\))?(!)?:( ?)(.*)$/;

/**
 * Why a commit is not judged. `null` means it IS judged.
 *
 * Merge detection is structural — `parents >= 2` — and not a match on
 * "Merge …", because a subject is editable and the parent count is not. A
 * commit that merely SAYS "Merge our two code paths into one" is an ordinary
 * commit and is judged like one.
 */
export function exemption(commit) {
  if ((commit.parents ?? 1) >= 2) return 'a merge commit';
  if (/^Revert "/.test(commit.subject)) return 'a generated revert';
  return null;
}

/**
 * `{ ok: true }`, `{ ok: true, exempt }`, or `{ ok: false, reason }`.
 *
 * The reason names what is wrong with THIS subject rather than restating the
 * convention, because "does not follow Conventional Commits" is the one message
 * that tells somebody staring at their own subject line nothing at all.
 */
export function judge(commit) {
  const exempt = exemption(commit);
  if (exempt) return { ok: true, exempt };

  const subject = commit.subject ?? '';
  const m = SUBJECT.exec(subject);
  if (!m) {
    // SHORT, deliberately: this reason repeats on every prose subject in a
    // branch, and the list of types belongs once at the bottom rather than
    // nine times up the page.
    return { ok: false, reason: 'no "type: " prefix' };
  }
  const [, type, scope, , space, summary] = m;
  if (type !== type.toLowerCase()) {
    return { ok: false, reason: `the type must be lower-case, not "${type}"` };
  }
  if (!TYPES.includes(type)) {
    return { ok: false, reason: `"${type}" is not one of ${TYPES.join(', ')}` };
  }
  if (scope === '()') {
    return { ok: false, reason: 'an empty scope "()" — name it or leave it off' };
  }
  if (space !== ' ') {
    return { ok: false, reason: 'a space is required after the colon' };
  }
  if (summary.trim() === '') {
    return { ok: false, reason: 'the summary after the colon is empty' };
  }
  return { ok: true };
}

/** Every commit in `base..head`, newest first, with its parent count. */
export function commitsIn(base, head) {
  const RECORD = '\u001e';
  const FIELD = '\u001f';
  const out = execFileSync(
    'git',
    ['log', `--format=%H${FIELD}%P${FIELD}%s${RECORD}`, `${base}..${head}`],
    { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  return out
    .split(RECORD)
    .map((r) => r.replace(/^\n/, ''))
    .filter((r) => r.trim() !== '')
    .map((r) => {
      const [sha, parents, subject] = r.split(FIELD);
      return {
        sha: sha ?? '',
        parents: (parents ?? '').trim() === '' ? 0 : (parents ?? '').trim().split(/\s+/).length,
        subject: subject ?? '',
      };
    });
}

/** The lines this prints, as data, so the test can read them. */
export function report(commits) {
  const lines = [];
  const bad = [];
  for (const c of commits) {
    const v = judge(c);
    const short = c.sha.slice(0, 8);
    if (!v.ok) {
      bad.push({ ...c, reason: v.reason });
      lines.push(`  ✗ ${short}  ${c.subject}`);
      lines.push(`             ${v.reason}`);
    } else if (v.exempt) {
      lines.push(`  – ${short}  ${c.subject}   (${v.exempt}, not judged)`);
    } else {
      lines.push(`  ✓ ${short}  ${c.subject}`);
    }
  }
  return { lines, bad };
}

/* c8 ignore start — the CLI half; the pure half above is what the tests read. */
const invokedDirectly = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop());
if (invokedDirectly) {
  const [, , base, head] = process.argv;
  if (!base || !head) {
    console.error('usage: node scripts/commit-convention.mjs <base-ref> <head-ref>');
    process.exit(2);
  }
  const commits = commitsIn(base, head);
  if (commits.length === 0) {
    console.log(`No commits in ${base}..${head}. Nothing to check.`);
    process.exit(0);
  }
  const { lines, bad } = report(commits);
  console.log(`Commit subjects this branch adds (${commits.length}):\n`);
  console.log(lines.join('\n'));
  console.log('');
  for (const c of bad) {
    console.log(`::error::${c.sha.slice(0, 8)} "${c.subject}" — ${c.reason}`);
  }
  if (bad.length > 0) {
    console.log(
      `\n${bad.length} of ${commits.length} commit subject(s) do not follow Conventional Commits,\n` +
        'which CONTRIBUTING.md and the pull-request template both require.\n\n' +
        `A subject starts with one of: ${TYPES.join(', ')} — optionally a (scope),\n` +
        'an optional ! for a breaking change, then a colon, a space and the summary.\n\n' +
        'Nothing on main is being re-judged and no history needs rewriting — this reads\n' +
        'only the commits this branch adds. To fix, reword them on this branch:\n\n' +
        `    git rebase -i ${base}        # "reword" each one listed above\n` +
        '    git push --force-with-lease  # only ever on a branch you opened\n',
    );
    process.exit(1);
  }
  console.log('Every commit this branch adds follows the convention.');
}
/* c8 ignore stop */
